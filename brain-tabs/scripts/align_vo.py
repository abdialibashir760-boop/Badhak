"""Align the supplied voice-over (vo/voiceover.wav) to the script lines in vo/script.txt.

1. speech segments from ffmpeg silence detection;
2. syllable-like energy peaks inside every segment (counted from the audio itself);
3. dynamic programming assigns contiguous segments to script lines so that the audio's syllable count matches
   each line's syllable count (merging across a long pause costs extra).
Writes src/data/voice.json  { duration, lines: [{i, text, start, end}] }  — consumed by src/scene.js and render.js."""
import json, math, os, re, subprocess, wave
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WAV = os.path.join(ROOT, "vo/voiceover.wav")
lines = [l.strip() for l in open(os.path.join(ROOT, "vo/script.txt"), encoding="utf-8").read().splitlines() if l.strip()]

w = wave.open(WAV); sr = w.getframerate(); x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
dur = len(x) / sr
r = subprocess.run(["ffmpeg", "-hide_banner", "-i", WAV, "-af", "silencedetect=noise=-35dB:d=0.15", "-f", "null", "-"], capture_output=True, text=True)
st = [float(v) for v in re.findall(r"silence_start: ([0-9.]+)", r.stderr)]
en = [float(v) for v in re.findall(r"silence_end: ([0-9.]+)", r.stderr)]
segs, cur = [], 0.0
for s, e in zip(st, en):
    if s - cur > 0.08: segs.append((cur, s))
    cur = e
if dur - cur > 0.08: segs.append((cur, dur))

hop = int(0.005 * sr); n = len(x) // hop
env = np.sqrt((x[: n * hop].reshape(n, hop) ** 2).mean(1)); env = np.convolve(env, np.ones(6) / 6, mode="same")
peaks = []
for i in range(3, n - 3):
    if env[i] > 0.02 and env[i] == env[max(0, i - 8): i + 9].max() and env[i] > 0.33 * env[max(0, i - 60): i + 60].max():
        t = i * 0.005
        if not peaks or t - peaks[-1] > 0.09: peaks.append(t)
peaks = np.array(peaks)

SPECIAL = {"am": 2, "3": 1, "twenties": 3, "eleven": 3, "email": 2, "landlord": 2, "loophole": 2}
def syl(wd):
    lw = re.sub(r"[^a-z0-9]", "", wd.lower())
    if lw in SPECIAL: return SPECIAL[lw]
    c = len(re.findall(r"[aeiouy]+", lw))
    if lw.endswith("e") and not lw.endswith("le") and c > 1: c -= 1
    return max(1, c)
S = [sum(syl(wd) for wd in re.findall(r"[A-Za-z0-9']+", l)) for l in lines]
P = [int(((peaks >= a - 0.02) & (peaks <= b + 0.02)).sum()) for a, b in segs]
print(f"{len(lines)} lines ({sum(S)} syllables), {len(segs)} segments ({sum(P)} syllable peaks)")

nL, nS, INF = len(lines), len(segs), 1e18
dp = [[INF] * (nS + 1) for _ in range(nL + 1)]; bk = [[None] * (nS + 1) for _ in range(nL + 1)]; dp[0][0] = 0
for i in range(1, nL + 1):
    for j in range(1, nS + 1):
        for c in range(1, 11):
            a = j - c
            if a < 0 or dp[i - 1][a] >= INF: continue
            p = sum(P[a:j]); gaps = sum(segs[q][0] - segs[q - 1][1] for q in range(a + 1, j))
            cost = (p - S[i - 1]) ** 2 / (S[i - 1] + 2) + 0.05 * (c - 1) + 1.4 * gaps * gaps
            if dp[i - 1][a] + cost < dp[i][j]: dp[i][j] = dp[i - 1][a] + cost; bk[i][j] = a
j, assign = nS, []
for i in range(nL, 0, -1): a = bk[i][j]; assign.append((a, j)); j = a
assign.reverse()
# Manual correction after listening to the segment structure: "Why now?" is the lone segment after the long pause,
# and "Berlin, / nineteen twenties." is the next two segments (the DP's syllable counter over-counts the slow "Why now?").
OVERRIDE = {1: (1, 2), 2: (2, 3), 3: (3, 5)}
for li, rng in OVERRIDE.items():
    if assign[li] != rng and os.environ.get("NO_OVERRIDE") is None: assign[li] = rng
out = []
for i, (a, b) in enumerate(assign):
    out.append({"i": i, "text": lines[i], "start": round(segs[a][0], 3), "end": round(segs[b - 1][1], 3)})
    print(f"{i:2d} {segs[a][0]:6.2f}-{segs[b-1][1]:6.2f}  syl {sum(P[a:b]):2d}/{S[i]:2d}  {b-a}seg  {lines[i][:50]}")
os.makedirs(os.path.join(ROOT, "src/data"), exist_ok=True)
json.dump({"duration": dur, "lines": out}, open(os.path.join(ROOT, "src/data/voice.json"), "w"), indent=1)
# anchors consumed by src/scene.js (works as a <script> in the browser and via require() in Node)
anch = {"starts": [o["start"] for o in out], "end": out[-1]["end"], "total": round(dur + 0.9, 3)}
open(os.path.join(ROOT, "src/voice_anchors.js"), "w").write("/* generated by scripts/align_vo.py */\n(function (r) { var a = " + json.dumps(anch) + "; if (typeof module === 'object' && module.exports) module.exports = a; else r.VOICE_ANCHORS = a; })(typeof self !== 'undefined' ? self : this);\n")
