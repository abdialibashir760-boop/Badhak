"""Shared narration + mix pipeline. A story module supplies ID, LINES, VOICE, SPEED, LEAD, TAIL and sound(ctx)."""
import json
import subprocess
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = Path(__file__).resolve().parent.parent
SR = 24000


def srt_time(t: float) -> str:
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def build(story, model: str, voices: str, lang: str = "en-us") -> None:
    k = Kokoro(model, voices)
    clips = []
    for lid, say, cap, gap in story.LINES:
        s, sr = k.create(say, voice=story.VOICE, speed=story.SPEED, lang=lang)
        assert sr == SR
        idx = np.where(np.abs(s) > 0.01)[0]  # trim silence so line timing is tight
        s = s[max(0, idx[0] - int(0.03 * SR)) : idx[-1] + int(0.08 * SR)]
        clips.append((lid, s.astype(np.float32), cap, gap))

    t = story.LEAD
    timeline = []
    for lid, s, cap, gap in clips:
        dur = len(s) / SR
        timeline.append({"id": lid, "cap": cap, "start": round(t, 3), "end": round(t + dur, 3)})
        t += dur + gap
    narration_end = timeline[-1]["end"]
    total = narration_end + story.TAIL

    n = int(total * SR)
    voice = np.zeros(n, dtype=np.float32)
    for (_, s, _, _), tl in zip(clips, timeline):
        a = int(tl["start"] * SR)
        voice[a : a + len(s)] += s
    voice *= 0.89 / np.abs(voice).max()

    rng = np.random.default_rng(7)
    tt = np.arange(n) / SR

    def env(start, dur, a=0.05, r=0.4):
        e = np.zeros(n, dtype=np.float32)
        i0, i1 = int(start * SR), min(n, int((start + dur) * SR))
        m = i1 - i0
        x = np.ones(m, dtype=np.float32)
        na, nr = int(a * SR), int(r * SR)
        x[:na] = np.linspace(0, 1, na)
        x[-nr:] *= np.linspace(1, 0, nr)
        e[i0:i1] = x
        return e

    def lowpass_noise(cut_hz):
        w = rng.standard_normal(n).astype(np.float32)
        k_ = int(SR / cut_hz)
        return np.convolve(w, np.ones(k_) / k_, mode="same").astype(np.float32)

    ctx = SimpleNamespace(n=n, SR=SR, tt=tt, at={tl["id"]: tl for tl in timeline}, total=total, env=env, lowpass_noise=lowpass_noise, rng=rng)
    bed, fx = story.sound(ctx)

    # duck bed + fx a little where narration plays
    vm = np.convolve(np.abs(voice), np.ones(int(0.25 * SR)) / int(0.25 * SR), mode="same")
    duck = 1.0 - 0.35 * np.clip(vm / 0.08, 0, 1)
    mix = np.tanh((voice + (bed + fx) * duck) * 1.05) * 0.95

    out = ROOT / "out"
    out.mkdir(exist_ok=True)
    (ROOT / "src" / story.ID).mkdir(parents=True, exist_ok=True)
    wav = out / f"{story.ID}.wav"
    sf.write(wav, mix, SR)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-ac", "1", "-b:a", "128k", str(ROOT / "public" / f"{story.ID}.mp3")], check=True)

    ts = "// Generated by scripts/make_audio.py — do not edit by hand.\n"
    ts += "export type Line = { id: string; cap: string; start: number; end: number };\n"
    ts += f"export const NARRATION_END = {narration_end};\nexport const TOTAL_SECONDS = {round(total, 3)};\n"
    ts += "export const LINES: Line[] = " + json.dumps(timeline, ensure_ascii=False, indent=2) + ";\n"
    (ROOT / "src" / story.ID / "timeline.ts").write_text(ts)

    srt = "".join(f"{i}\n{srt_time(tl['start'])} --> {srt_time(tl['end'])}\n{tl['cap']}\n\n" for i, tl in enumerate(timeline, 1))
    (out / f"{story.ID}.srt").write_text(srt)
    print(f"{story.ID}: narration ends {narration_end:.1f}s, total {total:.1f}s, {len(timeline)} lines")
