// Rasterises Natural Earth 1:50m land (via the `world-atlas` package, public domain)
// into a run-length-encoded equirectangular mask used for the dot-matrix globe.
//   node scripts/build-land.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const STEP = 0.125; // degrees per cell
const W = Math.round(360 / STEP);
const H = Math.round(180 / STEP);

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8"));
const land = feature(topo, topo.objects.land);

// Collect every ring (outer rings and holes alike): even-odd fill handles holes.
const rings = [];
const collect = (geom) => {
  if (geom.type === "Polygon") rings.push(...geom.coordinates);
  else if (geom.type === "MultiPolygon") geom.coordinates.forEach((p) => rings.push(...p));
};
if (land.type === "FeatureCollection") land.features.forEach((f) => collect(f.geometry));
else collect(land.geometry);

// Bucket edges per scanline for speed.
const edgesByRow = Array.from({ length: H }, () => []);
for (const ring of rings) {
  for (let i = 0; i < ring.length - 1; i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[i + 1];
    if (y1 === y2) continue;
    const yLo = Math.min(y1, y2);
    const yHi = Math.max(y1, y2);
    const r0 = Math.max(0, Math.floor((90 - yHi) / STEP));
    const r1 = Math.min(H - 1, Math.ceil((90 - yLo) / STEP));
    for (let r = r0; r <= r1; r++) edgesByRow[r].push([x1, y1, x2, y2]);
  }
}

const mask = new Uint8Array(W * H);
for (let r = 0; r < H; r++) {
  const lat = 90 - (r + 0.5) * STEP;
  const xs = [];
  for (const [x1, y1, x2, y2] of edgesByRow[r]) {
    if ((y1 <= lat && y2 > lat) || (y2 <= lat && y1 > lat)) {
      xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const c0 = Math.max(0, Math.round((xs[k] + 180) / STEP));
    const c1 = Math.min(W, Math.round((xs[k + 1] + 180) / STEP));
    for (let c = c0; c < c1; c++) mask[r * W + c] = 1;
  }
}

// Run-length encode (alternating sea/land runs, starting with sea), base-36.
const runs = [];
let cur = 0;
let len = 0;
for (let i = 0; i < mask.length; i++) {
  if (mask[i] === cur) len++;
  else {
    runs.push(len);
    cur = mask[i];
    len = 1;
  }
}
runs.push(len);

const encoded = runs.map((n) => n.toString(36)).join(",");
const out = `// GENERATED by scripts/build-land.mjs — do not edit.
// Natural Earth 1:50m land (public domain), rasterised to an equirectangular
// mask, ${W}x${H} cells (${STEP}° per cell), run-length encoded (sea first).
export const LAND_STEP = ${STEP};
export const LAND_W = ${W};
export const LAND_H = ${H};
export const LAND_RLE = "${encoded}";
`;
writeFileSync("src/landData.ts", out);
const landCells = mask.reduce((a, b) => a + b, 0);
console.log(`runs=${runs.length} bytes=${out.length} landFraction=${(landCells / mask.length).toFixed(3)}`);
