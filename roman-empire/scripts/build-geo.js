#!/usr/bin/env node
/*
 * Builds src/geo.js — simplified land polygons (Natural Earth 1:50m via world-atlas) cropped to the
 * area the camera can see. Only needed if you want to regenerate the coastline:  npm i && npm run build:geo
 */
const fs = require('fs'), path = require('path');
const topo = require('topojson-client');
const land = require('world-atlas/land-50m.json');

const BBOX = [-58, -2, 98, 84];   // lon0, lat0, lon1, lat1  (a little larger than the widest camera view)
const TOL = 0.025;                // Douglas–Peucker tolerance in degrees
const MIN_AREA = 0.004;           // drop specks smaller than this (deg²)

function clip(ring, [x0, y0, x1, y1]) {                     // Sutherland–Hodgman against the bbox
  const edges = [
    [(p) => p[0] >= x0, (a, b) => [x0, a[1] + ((b[1] - a[1]) * (x0 - a[0])) / (b[0] - a[0])]],
    [(p) => p[0] <= x1, (a, b) => [x1, a[1] + ((b[1] - a[1]) * (x1 - a[0])) / (b[0] - a[0])]],
    [(p) => p[1] >= y0, (a, b) => [a[0] + ((b[0] - a[0]) * (y0 - a[1])) / (b[1] - a[1]), y0]],
    [(p) => p[1] <= y1, (a, b) => [a[0] + ((b[0] - a[0]) * (y1 - a[1])) / (b[1] - a[1]), y1]],
  ];
  let out = ring.slice(0, -1);
  for (const [inside, cut] of edges) {
    const inp = out; out = [];
    for (let i = 0; i < inp.length; i++) {
      const a = inp[i], b = inp[(i + 1) % inp.length];
      if (inside(b)) { if (!inside(a)) out.push(cut(a, b)); out.push(b); } else if (inside(a)) out.push(cut(a, b));
    }
    if (!out.length) break;
  }
  return out;
}
function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let dmax = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / len;
      if (d > dmax) { dmax = d; idx = i; }
    }
    if (dmax > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0)) / 2;

const fc = topo.feature(land, land.objects.land);
const feats = fc.features || [fc];
const rings = []; 
for (const f of feats) {
  const g = f.geometry; const polys = g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates];
  for (const poly of polys) for (const ring of poly) {
    const c = clip(ring, BBOX); if (c.length < 3) continue;
    let far = 1; for (let i = 2; i < c.length; i++) if (Math.hypot(c[i][0] - c[0][0], c[i][1] - c[0][1]) > Math.hypot(c[far][0] - c[0][0], c[far][1] - c[0][1])) far = i;
    const s = dp(c.slice(0, far + 1), TOL).slice(0, -1).concat(dp(c.slice(far).concat([c[0]]), TOL).slice(0, -1));   // closed ring: simplify two chains
    if (s.length < 3 || area(s) < MIN_AREA) continue;
    rings.push(s);
  }
}
const r2 = (n) => Math.round(n * 100) / 100;
const body = rings.map((r) => '[' + r.map((p) => r2(p[0]) + ',' + r2(p[1])).join(',') + ']').join(',\n');
const out = `/* Generated by scripts/build-geo.js from Natural Earth 1:50m land (public domain) via world-atlas. Flat [lon,lat,…] rings. */
(function (root, data) {
  if (typeof module === 'object' && module.exports) module.exports = data; else root.ROME_GEO = data;
})(typeof self !== 'undefined' ? self : this, { rings: [
${body}
] });
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'geo.js'), out);
console.log(`${rings.length} rings, ${rings.reduce((n, r) => n + r.length, 0)} points, ${(out.length / 1024).toFixed(0)} KB`);
