// Builds src/map/geo.generated.ts: simplified land rings + modern country borders (Natural Earth 1:50m, public domain, via world-atlas).
import fs from 'node:fs'; import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const topo = require('topojson-client'); const land = require('world-atlas/land-50m.json'); const countries = require('world-atlas/countries-50m.json');
const BBOX = [-110, -45, 150, 84], TOL = 0.03, MIN_AREA = 0.01;
function clip(ring, [x0, y0, x1, y1]) {
  const edges = [[(p) => p[0] >= x0, (a, b) => [x0, a[1] + ((b[1] - a[1]) * (x0 - a[0])) / (b[0] - a[0])]], [(p) => p[0] <= x1, (a, b) => [x1, a[1] + ((b[1] - a[1]) * (x1 - a[0])) / (b[0] - a[0])]],
    [(p) => p[1] >= y0, (a, b) => [a[0] + ((b[0] - a[0]) * (y0 - a[1])) / (b[1] - a[1]), y0]], [(p) => p[1] <= y1, (a, b) => [a[0] + ((b[0] - a[0]) * (y1 - a[1])) / (b[1] - a[1]), y1]]];
  let out = ring.slice(0, -1);
  for (const [inside, cut] of edges) { const inp = out; out = []; for (let i = 0; i < inp.length; i++) { const a = inp[i], b = inp[(i + 1) % inp.length]; if (inside(b)) { if (!inside(a)) out.push(cut(a, b)); out.push(b); } else if (inside(a)) out.push(cut(a, b)); } if (!out.length) break; }
  return out;
}
function dp(pts, tol) {
  if (pts.length < 3) return pts; const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1; const st = [[0, pts.length - 1]];
  while (st.length) { const [a, b] = st.pop(); let dm = 0, ix = -1; const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / len; if (d > dm) { dm = d; ix = i; } } if (dm > tol) { keep[ix] = 1; st.push([a, ix], [ix, b]); } }
  return pts.filter((_, i) => keep[i]);
}
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0)) / 2;
const r2 = (n) => Math.round(n * 100) / 100;
const rings = [];
for (const f of topo.feature(land, land.objects.land).features) for (const poly of f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]) for (const ring of poly) {
  const c = clip(ring, BBOX); if (c.length < 3) continue; let far = 1;
  for (let i = 2; i < c.length; i++) if (Math.hypot(c[i][0] - c[0][0], c[i][1] - c[0][1]) > Math.hypot(c[far][0] - c[0][0], c[far][1] - c[0][1])) far = i;
  const s = dp(c.slice(0, far + 1), TOL).slice(0, -1).concat(dp(c.slice(far).concat([c[0]]), TOL).slice(0, -1));
  if (s.length < 3 || area(s) < MIN_AREA) continue; rings.push(s.flatMap((p) => [r2(p[0]), r2(p[1])]));
}
// modern internal borders (shared arcs between two different countries), clipped to the view box
const mesh = topo.mesh(countries, countries.objects.countries, (a, b) => a !== b);
const borders = [];
for (const line of mesh.coordinates) { let cur = [];
  const flush = () => { if (cur.length > 1) borders.push(dp(cur, 0.04).flatMap((p) => [r2(p[0]), r2(p[1])])); cur = []; };
  for (const p of line) { if (p[0] > BBOX[0] && p[0] < BBOX[2] && p[1] > BBOX[1] && p[1] < BBOX[3]) cur.push(p); else flush(); } flush(); }
const out = `// GENERATED by tools/build-geo.mjs — Natural Earth 1:50m (public domain) via world-atlas. Flat [lon,lat,…] arrays.\nexport const LAND_RINGS: number[][] = ${JSON.stringify(rings)};\nexport const MODERN_BORDERS: number[][] = ${JSON.stringify(borders)};\n`;
fs.writeFileSync(new URL('../src/map/geo.generated.ts', import.meta.url), out);
console.log(rings.length, 'rings', borders.length, 'border lines', (out.length / 1024).toFixed(0), 'KB');
