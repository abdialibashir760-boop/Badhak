export const YEARS: [number, number][] = [[0, -753], [1.9, -753], [2.15, -509], [2.7, -264], [3.4, -241], [3.9, -146], [4.6, -58], [5.4, -30], [6.0, 43], [6.6, 106], [7.2, 117]];
export const yearAtTau = (t: number) => {
  if (t <= YEARS[0][0]) return YEARS[0][1];
  for (let i = 1; i < YEARS.length; i++) if (t <= YEARS[i][0]) { const [t0, y0] = YEARS[i - 1], [t1, y1] = YEARS[i]; return y0 + ((y1 - y0) * (t - t0)) / (t1 - t0); }
  return YEARS[YEARS.length - 1][1];
};
export const fmtYear = (y: number) => { y = Math.round(y); if (y === 0) y = 1; return y < 0 ? `${-y} BCE` : `${y} CE`; };

